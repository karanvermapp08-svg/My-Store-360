/**
 * Ensures all AppUser records have salted passwordHash and NO plain-text password stored.
 */
export function sanitizeAndHashSeedUsers(rawUsers: AppUser[]): AppUser[] {
  let merged = [...rawUsers];
  for (const seedUser of DEFAULT_ROLE_PORTAL_USERS) {
    const code = (seedUser.employeeId || '').toUpperCase();
    if (!merged.some((u) => (u.employeeId || '').toUpperCase() === code || u.id === seedUser.id)) {
      merged.push(seedUser);
    }
  }

  return merged.map((u, idx) => {
    const accountType: 'ADMIN' | 'STAFF' =
      u.accountType ||
      (u.roleName === 'Owner' || u.roleName === 'Admin' || u.roleName === 'Administrator'
        ? 'ADMIN'
        : 'STAFF');

    let passwordHash = u.passwordHash;
    if (!isPasswordHashed(passwordHash)) {
      const seedPwd = u.password || 'emp@password123';
      const deterministicSalt = `b360${String(idx + 11).padStart(4, '0')}e7a901c2d48f6a12${String(u.id.length).padStart(4, '0')}abcd`;
      passwordHash = hashSeedPasswordSync(seedPwd, deterministicSalt);
    }

    const { password: _removedPlain, ...safeUser } = u;
    return {
      ...safeUser,
      accountType,
      passwordHash,
    };
  });
}

export function stripSecretFieldsFromUser(user: AppUser | null): AppUser | null {
  if (!user) return null;
  const { password: _p, passwordHash: _ph, ...safe } = user;
  return safe;
}

