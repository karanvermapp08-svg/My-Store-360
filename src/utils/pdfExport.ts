// 1. Export Transactions Report (Sales, Purchases, Quotations, Orders, etc.)
// ==========================================
export const exportTransactionsPdf = (
  transactions: Transaction[],
  company: CompanyProfile,
  title = 'Sale Invoices & Transactions Report',
  dateRange = 'Current Period'
) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const subInfo = `Period: ${dateRange}  |  Total Records: ${transactions.length}  |  Firm: ${company.name}`;
  const startY = drawOfficialHeader(doc, company, title, subInfo);

  // Financial Metrics Summary Box
  const totalAmount = transactions.reduce((acc, curr) => acc + (curr.totalAmount || 0), 0);
  const totalReceived = transactions.reduce((acc, curr) => acc + (curr.receivedAmount || 0), 0);
  const totalBalance = transactions.reduce((acc, curr) => acc + (curr.balance || 0), 0);

  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, startY, pageWidth - 28, 18, 2, 2, 'FD');

  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('Total Entries', 20, startY + 6);
  doc.text('Total Invoiced Amount', 65, startY + 6);
  doc.text('Amount Received', 120, startY + 6);
  doc.text('Outstanding Balance', 160, startY + 6);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`${transactions.length} Invoices`, 20, startY + 13);
  doc.text(fmtCur(totalAmount), 65, startY + 13);
  doc.setTextColor(22, 163, 74); // green
  doc.text(fmtCur(totalReceived), 120, startY + 13);
  doc.setTextColor(225, 29, 72); // rose
  doc.text(fmtCur(totalBalance), 160, startY + 13);

  // Data Table
  const tableData = transactions.map((t, idx) => [
    idx + 1,
    t.date,
    `#${t.invoiceNo}`,
    t.partyName,
    t.paymentType,
    fmtCur(t.totalAmount),
    fmtCur(t.balance),
    t.dueDate || '-',
    t.status,
  ]);

  autoTable(doc, {
    startY: startY + 22,
    head: [['#', 'Date', 'Invoice No', 'Party Name', 'Payment Mode', 'Amount', 'Balance', 'Due Date', 'Status']],
    body: tableData.length > 0 ? tableData : [['-', '-', '-', 'No transactions recorded', '-', '-', '-', '-', '-']],
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'left',
    },
    bodyStyles: {
      fontSize: 7.5,
      textColor: [51, 65, 85],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 8, halign: 'center' },
      1: { cellWidth: 20 },
      2: { cellWidth: 20, fontStyle: 'bold' },
      3: { cellWidth: 'auto' },
      4: { cellWidth: 22 },
      5: { cellWidth: 25, halign: 'right', fontStyle: 'bold' },
      6: { cellWidth: 25, halign: 'right', textColor: [225, 29, 72] },
      7: { cellWidth: 20, halign: 'center' },
      8: { cellWidth: 18, halign: 'center' },
    },
    margin: { left: 14, right: 14 },
  });

  const finalY = (doc as any).lastAutoTable?.finalY || startY + 60;
  drawSignatory(doc, company, finalY);
  addPageFooters(doc, company);

  const safeFilename = title.toLowerCase().replace(/[^a-z0-9]/g, '_');
  doc.save(`${safeFilename}_${new Date().toISOString().slice(0, 10)}.pdf`);
};

