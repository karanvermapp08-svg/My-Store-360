/** Helper: Format numbers to Indian currency display without crashing on null/undefined */
const fmtCur = (num: number | undefined | null) => {
  return 'Rs. ' + (Number(num) || 0).toLocaleString('en-IN');
};

/** Helper: Draw standard Vyapar official header & letterhead */
const drawOfficialHeader = (
  doc: jsPDF,
  company: CompanyProfile,
  reportTitle: string,
  subInfo: string
) => {
  const pageWidth = doc.internal.pageSize.getWidth();

  // Dark slate top banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Red accent indicator stripe
  doc.setFillColor(225, 29, 72); // rose-600
  doc.rect(0, 27, pageWidth, 1.2, 'F');

  // Company Name
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text((company.name || 'ENTERPRISE').toUpperCase(), 14, 11);

  // Address and Contact
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // slate-300
  const contactText = `${company.address || 'Business Address'} | Phone: ${company.phone || 'N/A'} | Email: ${company.email || 'N/A'}`;
  doc.text(contactText, 14, 17);

  const gstText = `GSTIN: ${company.gstin || 'Unregistered'} | State: ${company.state || 'Karnataka'}`;
  doc.text(gstText, 14, 23);

  // Right Side: Business Manager 360 Official Tag
  doc.setTextColor(96, 165, 250); // blue-400
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('BUSINESS MANAGER 360', pageWidth - 14, 11, { align: 'right' });

  doc.setTextColor(148, 163, 184); // slate-400
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.text('OFFICIAL RECORD & AUDIT DOCUMENT', pageWidth - 14, 17, { align: 'right' });
  doc.text(`Generated: ${new Date().toLocaleDateString('en-GB')} ${new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`, pageWidth - 14, 23, { align: 'right' });

  // Subheader title
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(reportTitle, 14, 37);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text(subInfo, 14, 43);

  return 47; // next Y position
};

/** Helper: Draw page footer on every page */
const addPageFooters = (doc: jsPDF, company: CompanyProfile) => {
  const pageCount = (doc as any).internal.getNumberOfPages();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);

    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);
    doc.text(
      `Generated by Business Manager 360  |  ${company.name}  |  Page ${i} of ${pageCount}`,
      pageWidth / 2,
      pageHeight - 7,
      { align: 'center' }
    );
  }
};

/** Helper: Draw Authorized Signatory Stamp Box at bottom */
const drawSignatory = (doc: jsPDF, company: CompanyProfile, startY: number) => {
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  let signY = startY + 10;
  if (signY > pageHeight - 35) {
    doc.addPage();
    signY = 30;
  }

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(`For ${company.name}`, pageWidth - 14, signY, { align: 'right' });
  doc.line(pageWidth - 65, signY + 12, pageWidth - 14, signY + 12);
  doc.text('Authorized Signatory', pageWidth - 14, signY + 16, { align: 'right' });
};

