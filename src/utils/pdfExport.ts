// 2. Export Individual Party Statement / Account Ledger
// ==========================================
export const exportPartyStatementPdf = (
  party: Party,
  partyTransactions: Transaction[],
  company: CompanyProfile,
  dateRange = 'Current Financial Period',
  businessSettings?: BusinessSettingsBundle
) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const title = `STATEMENT OF ACCOUNT - ${party.name.toUpperCase()}`;
  const subInfo = `Period: ${dateRange}  |  ${party.groupName ? `Group: ${party.groupName}  |  ` : ''}Status: ${party.status || 'Active'}`;
  const startY = drawOfficialHeader(doc, company, title, subInfo);

  const printableCustomFields = (businessSettings?.party?.additionalFields || []).filter(
    (f) => f.enabled && f.showInPrint && party.customFields?.[f.id]
  );
  const showShipping =
    businessSettings?.party?.enableShippingAddress &&
    businessSettings?.print?.showShippingAddress !== false &&
    Boolean(party.shippingAddress || party.shippingAddresses?.[0]?.address);
  const cardHeight = 23 + (showShipping ? 5 : 0) + (printableCustomFields.length > 0 ? 6 : 0);

  // Party Profile Info Card
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, startY, pageWidth - 28, cardHeight, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`Party: ${party.name}${party.groupName ? ` (${party.groupName})` : ''}`, 18, startY + 6);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`Contact Phone: ${party.phone || 'N/A'}  |  Email: ${party.email || 'N/A'}`, 18, startY + 11);
  doc.text(`Billing Address: ${party.address || 'Local Customer'}`, 18, startY + 16);
  let nextInfoY = startY + 20;
  if (showShipping) {
    const shipText = party.shippingAddress || party.shippingAddresses?.[0]?.address || '';
    doc.text(`Shipping Address: ${shipText}`, 18, nextInfoY);
    nextInfoY += 4.5;
  }
  doc.text(`GSTIN: ${party.gstin || 'Unregistered / Consumer'}`, 18, nextInfoY);
  if (printableCustomFields.length > 0) {
    const customSummary = printableCustomFields
      .map((f) => `${f.name}: ${party.customFields?.[f.id]}`)
      .join('  |  ');
    doc.text(customSummary, 18, nextInfoY + 4.5);
  }

  // Right Side: Outstanding Balance Callout
  const balanceX = pageWidth - 65;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('CURRENT OUTSTANDING BALANCE', balanceX, startY + 6);

  doc.setFontSize(12);
  const isReceivable = (party.balance || 0) >= 0;
  doc.setTextColor(isReceivable ? 225 : 22, isReceivable ? 29 : 163, isReceivable ? 72 : 74);
  doc.text(
    `${fmtCur(Math.abs(party.balance || 0))} ${isReceivable ? '(Dr / Receivable)' : '(Cr / Payable)'}`,
    balanceX,
    startY + 15
  );

  const tableStartY = startY + cardHeight + 4;

  // Transaction Ledger Table
  let runningBalance = party.balance || 0;
  const tableData = partyTransactions.map((tx, idx) => {
    const isDebit = tx.type === 'Sale' || tx.type === 'Sale Order';
    const amount = tx.totalAmount || 0;
    if (isDebit) {
      runningBalance += amount - (tx.receivedAmount || 0);
    } else {
      runningBalance -= amount;
    }

    return [
      idx + 1,
      tx.date,
      tx.type,
      `#${tx.invoiceNo}`,
      tx.paymentType,
      isDebit ? fmtCur(amount) : '-',
      !isDebit ? fmtCur(amount) : fmtCur(tx.receivedAmount),
      fmtCur(tx.balance),
      tx.status,
    ];
  });

  autoTable(doc, {
    startY: tableStartY,
    head: [['#', 'Date', 'Type', 'Ref No', 'Mode', 'Billed (Dr)', 'Received (Cr)', 'Balance', 'Status']],
    body: tableData.length > 0 ? tableData : [['-', '-', '-', '-', '-', '-', '-', fmtCur(party.balance), 'No transactions recorded']],
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'left',
    },
    bodyStyles: {
      fontSize: 7.5,
      textColor: [51, 65, 85],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 8, halign: 'center' },
      1: { cellWidth: 20 },
      2: { cellWidth: 22 },
      3: { cellWidth: 20, fontStyle: 'bold' },
      4: { cellWidth: 20 },
      5: { cellWidth: 25, halign: 'right' },
      6: { cellWidth: 25, halign: 'right' },
      7: { cellWidth: 25, halign: 'right', fontStyle: 'bold', textColor: [225, 29, 72] },
      8: { cellWidth: 17, halign: 'center' },
    },
    margin: { left: 14, right: 14 },
  });

  const finalY = (doc as any).lastAutoTable?.finalY || startY + 80;

  // Bank & Settlement details for the party
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, finalY + 8, 90, 24, 1.5, 1.5, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(15, 23, 42);
  doc.text('Payment Remittance Details:', 18, finalY + 13);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(71, 85, 105);
  doc.text(`Bank: ${company.bankName} | A/C: ${company.accountNo}`, 18, finalY + 18);
  doc.text(`IFSC: ${company.ifsc} | UPI ID: ${company.upiId}`, 18, finalY + 23);
  doc.text(`Please quote Party Ref: ${party.name} on transfer.`, 18, finalY + 28);

  drawSignatory(doc, company, finalY + 8);
  addPageFooters(doc, company);

  const safeFilename = `Statement_${party.name.replace(/[^a-z0-9]/gi, '_')}`;
  doc.save(`${safeFilename}_${new Date().toISOString().slice(0, 10)}.pdf`);
};

