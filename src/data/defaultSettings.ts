export function interpolateMessageTemplate(
  template: string,
  vars: Record<string, string | number | undefined>
): string {
  if (!template) return '';
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => {
    const val = vars[key];
    return val !== undefined && val !== null && String(val) !== '' ? String(val) : match;
  });
}

